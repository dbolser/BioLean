"""Stage 4: grounded statements -> one Lean 4 source file of BioLean `Statement`s."""

import re
from datetime import date
from itertools import groupby

from biolean.ground import GroundedStatement, Grounding

LEAN_KIND = {
    "chemical": ".chemical", "protein": ".protein", "gene": ".gene", "process": ".process",
    "phenotype": ".phenotype", "disease": ".disease", "anatomy": ".anatomy", "cell_type": ".cellType",
}
# relation family -> object kinds the Lean `Target` constructor accepts
TARGET_KINDS = {"activity": {"protein"}, "amount": {"chemical", "protein"}, "process": {"process"}, "phenotype": {"phenotype"}}
EVIDENCE_KIND = {
    "meta_analysis": ".metaAnalysis", "rct": ".rct", "mechanistic": ".mechanistic", "observational": ".observational",
    "review": ".review", "in_vitro": ".inVitro", "other": ".observational",
}


def ident(curie: str) -> str:
    return curie.replace("UniProt:", "UP:").replace(":", "_")


def lean_str(s: str, cap: int | None = None) -> str:
    s = re.sub(r"\s+", " ", s).strip()
    if cap and len(s) > cap:
        s = s[: cap - 1] + "…"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def entity(g: Grounding) -> str:
    return f"def {ident(g.curie)} : Entity {LEAN_KIND[g.kind]} := ⟨{lean_str(g.curie)}, {lean_str(g.label)}⟩"


def check(s: GroundedStatement) -> str | None:
    """Reason the statement cannot be typed in Lean, or None."""
    family = s.relation.split("_", 1)[1]
    if s.object.kind in TARGET_KINDS[family]:
        return None
    if s.object.kind == "disease" and family == "phenotype":
        return f"disease object {s.object.curie} is not a phenotype in BioLean"
    return f"{family} needs a {'/'.join(sorted(TARGET_KINDS[family]))} object, got {s.object.kind} {s.object.curie}"


def key(s: GroundedStatement) -> tuple[str, str, str]:
    return s.subject.curie, s.relation, s.object.curie


def statement(n: int, group: list[GroundedStatement]) -> str:
    s = group[0]
    sid, family = f"S_{n:04d}", s.relation.split("_", 1)[1]
    sign, arrow = (".pos", "→+") if s.relation.startswith("increases") else (".neg", "→−")
    target = f"{family} of {s.object.label}" if family in ("activity", "amount") else s.object.label
    by_pmid = {e.pmid: e for e in reversed(group)}  # first statement per PMID wins
    evidence = ",\n".join(
        f"    {{ pmid := {e.pmid}, year := {e.year}, kind := {EVIDENCE_KIND[e.evidence_kind]}, "
        f"polarity := .{e.polarity}, note := {lean_str(e.quote, 300)} }}"
        for e in sorted(by_pmid.values(), key=lambda e: (e.year, e.pmid))
    )
    return (
        f"def {sid} : Statement where\n"
        f"  id := {lean_str(sid)}\n"
        f"  text := {lean_str(f'{s.subject.label} {arrow} {target}')}\n"
        f"  claim := .effect {ident(s.subject.curie)} {sign} (.{family} {ident(s.object.curie)})\n"
        f"  evidence := [\n{evidence}\n  ]\n"
    )


def emit(statements: list[GroundedStatement], today: date, keep_hedged: bool = False) -> tuple[str, list[str]]:
    """Render the Lean file. Returns (source, log of skipped statements)."""
    log, kept = [], []
    for s in statements:
        reason = "hedged" if s.hedged and not keep_hedged else check(s)
        if reason:
            log.append(f"skip PMID {s.pmid} {s.subject.curie} {s.relation} {s.object.curie}: {reason}")
        else:
            kept.append(s)
    groups = [list(g) for _, g in groupby(sorted(kept, key=key), key=key)]
    entities = {ident(g.curie): entity(g) for s in kept for g in (s.subject, s.object)}
    names = [f"S_{n:04d}" for n in range(1, len(groups) + 1)]
    body = "\n".join(statement(n, g) for n, g in enumerate(groups, 1))
    source = (
        "import BioLean\n\n"
        f"/-! Generated by `biolean emit` on {today.isoformat()}. Do not edit by hand. -/\n\n"
        "namespace BioLean.Lib.Generated\n\n"
        + "".join(entities[k] + "\n" for k in sorted(entities))
        + "\n" + body + ("\n" if body else "")
        + f"def all : List Statement := [{', '.join(names)}]\n\n"
        "end BioLean.Lib.Generated\n"
    )
    return source, log
