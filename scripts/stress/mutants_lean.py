"""Program 04: the Lean typing detector, observed. Every control and mutant claim from data/stress/04/mutants.json is
emitted as a `Claim` term (the same text the round-2/3 emitters write) into data/stress/04/lean/MutantsEmitted.lean, with
its own entity definitions (kind from the emitters' prefix and GO-namespace rule), and compiled with `lake env lean`.
A claim that fails `by decide` on `Rel.accepts` or the `Target.activity` kind check, or a type mismatch (a process where
a site is needed), shows up as an error on its line. Writes data/stress/04/lean_typing.tsv.
Run from the repo root:  python3 -I scripts/stress/mutants_lean.py"""
import json, re, subprocess, pathlib, collections

REPO = pathlib.Path('/home/danbolser/Build/BioLean')
OUT = REPO / 'data/stress/04'
LEAN = OUT / 'lean/MutantsEmitted.lean'

def ename(c): return 'e_' + re.sub(r'[^A-Za-z0-9]', '_', c)
def q(s): return '"' + (s or '').replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    rows = json.load(open(OUT / 'mutants.json'))
    ents = {}
    for r in rows:
        for c, k in (r.get('ents') or {}).items(): ents.setdefault(c, k)
    lines = ['import BioLean.Context', '',
             '/-! Program 04, generated by `scripts/stress/mutants_lean.py`: every control and mutant claim of the mutation',
             'test, as the textbook emitters would write it. Compiled once to observe which ones Lean rejects; errors are',
             'expected here and are the measurement. Not part of any library. -/', '',
             'namespace BioLean.Stress.MutantsEmitted', 'open BioLean', '']
    lines += [f'def {ename(c)} : Entity .{k} := ⟨{q(c)}, {q(c)}⟩' for c, k in sorted(ents.items())]
    lines.append('')
    span = {}
    for r in rows:
        if not r.get('lean_claim'): continue
        name = 'm_' + re.sub(r'[^A-Za-z0-9]', '_', r['mid'])
        start = len(lines) + 1
        lines.append(f'-- {r["mid"]}: {r["note"][:120]}')
        lines.append(f'def {name} : Claim := {r["lean_claim"]}')
        span[r['mid']] = (start, len(lines))
    lines += ['', 'end BioLean.Stress.MutantsEmitted', '']
    LEAN.parent.mkdir(parents=True, exist_ok=True)
    LEAN.write_text('\n'.join(lines))
    res = subprocess.run(['lake', 'env', 'lean', str(LEAN.relative_to(REPO))], cwd=REPO, capture_output=True, text=True, timeout=600)
    errs = collections.defaultdict(list)
    for m in re.finditer(r'^[^\n]*MutantsEmitted\.lean:(\d+):(\d+): error: (.*?)(?=^[^\n]*MutantsEmitted\.lean:\d+:\d+: |\Z)', res.stdout + res.stderr, re.S | re.M):
        ln = int(m.group(1))
        mid = next((k for k, (a, b) in span.items() if a <= ln <= b), None)
        errs[mid].append(' '.join(m.group(3).split())[:300])
    out = ['# mid\tlean result\tdetail']
    for r in rows:
        mid = r['mid']
        if not r.get('lean_claim'): out.append(f'{mid}\tnot emitted\t{r.get("lean_emit") or r.get("not_loaded")}')
        elif mid in errs: out.append(f'{mid}\trejected\t{" | ".join(errs[mid])}')
        else: out.append(f'{mid}\taccepted\t')
    (OUT / 'lean_typing.tsv').write_text('\n'.join(out) + '\n')
    stray = errs.get(None)
    print(f'compiled {len(span)} claims; rejected {sum(1 for k in span if k in errs)}; not emitted {sum(1 for r in rows if not r.get("lean_claim"))}'
          + (f'; errors outside any claim: {stray[:3]}' if stray else ''))
    # pin: rewrite the file so it compiles cleanly, each rejected claim under #check_failure (an unexpected success
    # is an error), each accepted claim as a def (a new rejection is an error). Then compile again.
    out_lines = []
    for ln in lines:
        m = re.match(r'^def (m_\S+) : Claim := (.*)$', ln)
        if m:
            mid = next(k for k, (a, b) in span.items() if lines[b - 1] == ln)
            out_lines.append(f'#check_failure (({m.group(2)} : Claim))' if mid in errs else ln)
        else:
            out_lines.append(ln)
    out_lines[out_lines.index('test, as the textbook emitters would write it. Compiled once to observe which ones Lean rejects; errors are')] = \
        'test, as the textbook emitters would write it. Lean\'s verdict on each is pinned: a rejected claim sits under'
    out_lines[out_lines.index('expected here and are the measurement. Not part of any library. -/')] = \
        '`#check_failure`, an accepted one is a `def`, so any change in what Lean accepts is an error. Not in any library. -/'
    LEAN.write_text('\n'.join(out_lines))
    res2 = subprocess.run(['lake', 'env', 'lean', str(LEAN.relative_to(REPO))], cwd=REPO, capture_output=True, text=True, timeout=600)
    n_err = len(re.findall(r'MutantsEmitted\.lean:\d+:\d+: error', res2.stdout + res2.stderr))
    print(f'pinned file: exit {res2.returncode}, errors {n_err}, #check_failure {sum(1 for l in out_lines if l.startswith("#check_failure"))}')

if __name__ == '__main__': main()
