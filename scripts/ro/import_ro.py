"""Emit BioLean/RO.lean from ro.owl: relations with labels, inverses, transitivity, property chains,
and coarse domain/range sorts. Usage: uv run python scripts/ro/import_ro.py data/ro.owl BioLean/RO.lean"""
import re, sys, rdflib
from rdflib.namespace import OWL, RDFS, RDF
from rdflib.collection import Collection

src, out = sys.argv[1], sys.argv[2]
g = rdflib.Graph(); g.parse(src)
OBO = 'http://purl.obolibrary.org/obo/'

def rel(u, inv=False):
    """Lean term for a property IRI (or an owl:inverseOf blank node)."""
    if not isinstance(u, rdflib.URIRef):
        tgt = g.value(u, OWL.inverseOf)
        return rel(tgt, not inv) if tgt is not None else None
    m = re.fullmatch(OBO + r'(RO|BFO)_(\d+)', str(u))
    if not m: return None
    return f'⟨.{m.group(1).lower()}, {int(m.group(2))}, {"true" if inv else "false"}⟩'

props = sorted(p for p in g.subjects(RDF.type, OWL.ObjectProperty) if rel(p))
label = lambda u: str(g.value(u, RDFS.label) or '').replace('"', "'")

# coarse sort of a domain/range class
OCC = {'BFO_0000015', 'BFO_0000003', 'BFO_0000035', 'GO_0008150', 'GO_0003674', 'BFO_0000144'}
def sort_of(c):
    s = str(c).split('/')[-1]
    if s in OCC: return 'occurrent'
    if s.startswith(('BFO_0000040', 'BFO_0000004', 'BFO_0000002', 'BFO_0000030', 'UBERON', 'CL_', 'CHEBI', 'PR_', 'COB', 'OGMS', 'NCBITaxon', 'PATO', 'BFO_0000020', 'BFO_0000017', 'BFO_0000031', 'BFO_0000141', 'CARO', 'PO_', 'ENVO')): return 'continuant'
    return None

lines = ['import BioLean.Rel', '', '/-! # RO: the Relation Ontology as data', '',
 f'Generated by `scripts/ro/import_ro.py` from ro.owl ({len(props)} RO/BFO object properties). Do not edit.',
 'Relations are `Rel` values by numeric id; `inv = true` is the inverse property. Chains are OWL',
 'property-chain axioms `r₁ ∘ r₂ ⊑ r`. Sorts are a coarse reading of rdfs:domain / rdfs:range. -/',
 'namespace BioLean.RO', '',
 '/-- Labels for printing. -/', 'def labels : List (Rel × String) := [']
for p in props: lines.append(f'  ({rel(p)}, "{label(p)}"),')
lines[-1] = lines[-1].rstrip(',')
lines += [']', '', '/-- owl:inverseOf pairs. -/', 'def inverses : List (Rel × Rel) := [']
n_inv = 0
for s, o in g.subject_objects(OWL.inverseOf):
    if isinstance(s, rdflib.URIRef) and isinstance(o, rdflib.URIRef) and rel(s) and rel(o):
        lines.append(f'  ({rel(s)}, {rel(o)}),'); n_inv += 1
lines[-1] = lines[-1].rstrip(',')
lines += [']', '', '/-- owl:TransitiveProperty. -/', 'def transitive : List Rel := [']
trans = [p for p in g.subjects(RDF.type, OWL.TransitiveProperty) if rel(p)]
lines += [f'  {rel(p)},' for p in trans]; lines[-1] = lines[-1].rstrip(',')
lines += [']', '', '/-- Property chains `(premises, conclusion)`; premises may include inverses. -/',
 'def chains : List (List Rel × Rel) := [']
n_ch = 0; skipped = 0
for s, o in g.subject_objects(OWL.propertyChainAxiom):
    items = [rel(i) for i in Collection(g, o)]
    if rel(s) and all(items):
        lines.append(f'  ([{", ".join(items)}], {rel(s)}),  -- {label(s)}'); n_ch += 1
    else: skipped += 1
lines[-1] = lines[-1].replace('),  --', ')  --', 1) if lines[-1].endswith(label(s)) or True else lines[-1]
# fix trailing comma on last chain line
i = len(lines) - 1
lines[i] = re.sub(r'\),(\s+--)', r')\1', lines[i])
lines += [']', '', '/-- Coarse rdfs:domain / rdfs:range sorts. -/', 'def domains : List (Rel × RelSort) := [']
dom = []
for s, o in g.subject_objects(RDFS.domain):
    if rel(s) and sort_of(o): dom.append(f'  ({rel(s)}, .{sort_of(o)}),')
lines += dom; lines[-1] = lines[-1].rstrip(',')
lines += [']', '', 'def ranges : List (Rel × RelSort) := [']
rng = []
for s, o in g.subject_objects(RDFS.range):
    if rel(s) and sort_of(o): rng.append(f'  ({rel(s)}, .{sort_of(o)}),')
lines += rng; lines[-1] = lines[-1].rstrip(',')
lines += [']', '',
 '/-- May `r₁` then `r₂` be composed to `r₃`? A property chain, transitivity, or an `is_a` law. -/',
 'def chainOK (r₁ r₂ r₃ : Rel) : Bool :=',
 '  chains.contains ([r₁, r₂], r₃)',
 '  || (r₁ == r₂ && r₂ == r₃ && (transitive.contains r₃ || r₃ == Rel.isA))',
 '  || (r₁ == Rel.isA && r₂ == r₃)   -- subclass inherits the superclass relation',
 '  || (r₂ == Rel.isA && r₁ == r₃)   -- a relation to a subclass is one to the superclass', '',
 '/-- Is `r\'` the inverse of `r`: by flag, or by RO\'s declared owl:inverseOf (either direction)? -/',
 'def inverseOK (r r\' : Rel) : Bool :=',
 '  r\' == r.flip || inverses.contains (r, r\') || inverses.contains (r\', r)', '',
 'end BioLean.RO', '']
open(out, 'w').write('\n'.join(lines))
print(f'relations {len(props)}, inverses {n_inv}, transitive {len(trans)}, chains {n_ch} (skipped {skipped} with non-RO/BFO members), domains {len(dom)}, ranges {len(rng)}')
