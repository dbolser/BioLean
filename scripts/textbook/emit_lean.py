"""Turn every textbook claim binned 'now' into a Lean Statement and write one module per chapter, so
Lean checks the book: entity kinds, RO domain/range, target shapes. Usage:
  emit_lean.py <claims_m1_dir> <go.obo> <out_dir>
Prints what was emitted and what was skipped (ungrounded, unsupported ontology, unparsable Lean)."""
import json, glob, re, sys, collections, pathlib
src, go_obo, out = sys.argv[1], sys.argv[2], pathlib.Path(sys.argv[3])
out.mkdir(parents=True, exist_ok=True)

# GO namespace -> Kind
go_ns = {}
cur = None
for line in open(go_obo, encoding='utf-8'):
    if line.startswith('id: GO:'): cur = line[4:].strip()
    elif cur and line.startswith('namespace: '): go_ns[cur] = line[11:].strip(); cur = None
KIND_BY_NS = {'biological_process': 'process', 'molecular_function': 'function', 'cellular_component': 'component'}
def kind_of(curie):
    p = curie.split(':')[0]
    if p == 'GO': return KIND_BY_NS.get(go_ns.get(curie))
    return {'CHEBI': 'chemical', 'PR': 'protein', 'UniProt': 'protein', 'UNIPROT': 'protein', 'HGNC': 'gene', 'NCBIGene': 'gene',
            'SO': 'gene', 'MGI': 'gene', 'HP': 'phenotype', 'MP': 'phenotype', 'PATO': 'phenotype', 'OBA': 'phenotype',
            'MONDO': 'disease', 'DOID': 'disease', 'UBERON': 'anatomy', 'CL': 'cellType', 'NCBITaxon': 'taxon'}.get(p)

# RO label -> Rel term
ro_labels = {}
for m in re.finditer(r'\(⟨\.(ro|bfo), (\d+), false⟩, "([^"]+)"\)', open('BioLean/RO.lean').read()):
    ro_labels[m.group(3).lower()] = f'⟨.{m.group(1)}, {m.group(2)}, false⟩'
ro_labels['is_a'] = 'Rel.isA'; ro_labels['is a'] = 'Rel.isA'; ro_labels['subclass of'] = 'Rel.isA'
def rel_term(label):
    if not label: return None
    l = label.strip().lower().replace('_', ' ')
    return ro_labels.get(l) or ro_labels.get(l.replace('inverse(', '').rstrip(')'))

def ename(curie): return 'e_' + re.sub(r'[^A-Za-z0-9]', '_', curie)
def lean_str(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

stats = collections.Counter(); skipped = collections.Counter()
for path in sorted(glob.glob(f'{src}/*.json')):
    slug = pathlib.Path(path).stem
    mod = ''.join(w.capitalize() for w in re.split(r'[^a-z0-9]+', slug) if w)
    ents = {}   # curie -> (kind, label)
    defs = []
    for r in json.load(open(path)):
        b = r.get('bin_m1') or r.get('bin')
        if b != 'now': continue
        stats['now'] += 1
        lean = (r.get('lean_m1') if r.get('bin_m1') else r.get('lean')) or ''
        grounded = [(e['curie'], e.get('text') or '') for e in r.get('entities', []) if e.get('curie')]
        kinds = [(c, kind_of(c), t) for c, t in grounded]
        if any(k is None for _, k, _ in kinds):
            skipped['unsupported ontology or GO namespace'] += 1; continue
        if len(kinds) < 2:
            skipped['fewer than two grounded entities'] += 1; continue
        head = re.match(r'\s*(Claim\.(rel|notRel|effect|mediatedBy))\b(.*)', lean, re.S)
        if not head: skipped['no Lean head'] += 1; continue
        ctor = head.group(2); rest = head.group(3)
        for c, k, t in kinds:
            ents.setdefault(c, (k, t))
        a, bb = ename(kinds[0][0]), ename(kinds[1][0])
        if ctor in ('rel', 'notRel'):
            rt = rel_term(r.get('rel_m1') or r.get('relation'))
            if not rt:
                m = re.match(r'\s*Rel\.(\w+)', rest)
                rt = f'Rel.{m.group(1)}' if m else None
            if not rt: skipped['relation not in RO'] += 1; continue
            claim = f'.{ctor} {rt} {a} {bb}'
        else:
            msign = re.search(r'\.(pos|neg)\b', rest); mt = re.search(r'\(\.(activity|amount|process|phenotype|site)\s', rest)
            if not (msign and mt): skipped['effect without sign/target'] += 1; continue
            tgt = f'(.{mt.group(1)} {bb})'
            if ctor == 'mediatedBy':
                mm = re.findall(r'\(\.(activity|amount|process|phenotype|site)\s', rest)
                if len(mm) < 2 or len(kinds) < 3: skipped['mediatedBy without mediator'] += 1; continue
                claim = f'.mediatedBy {a} .{msign.group(1)} {tgt} (.{mm[1]} {ename(kinds[2][0])})'
            else:
                claim = f'.effect {a} .{msign.group(1)} {tgt}'
        sid = re.sub(r'[^A-Za-z0-9_]', '_', r['id'])
        text = (r.get('claim') or '')[:160]
        defs.append(f'/-- {text} -/\ndef {sid} : Statement where\n  id := {lean_str(r["id"])}\n  text := {lean_str(text)}\n'
                    f'  claim := {claim}\n  evidence := [{{ pmid := 0, year := 2013, kind := .textbook, note := {lean_str((r.get("source") or "")[:200])} }}]')
        stats['emitted'] += 1
    lines = ['import BioLean.Evidence', '', f'/-! Textbook claims, chapter `{slug}`, generated by `scripts/textbook/emit_lean.py`. Do not edit. -/', '',
             f'namespace BioLean.Textbook.{mod}', '', '-- entities']
    for c, (k, t) in sorted(ents.items()):
        lines.append(f'def {ename(c)} : Entity .{k} := ⟨{lean_str(c)}, {lean_str(t[:60])}⟩')
    lines += ['', '-- statements'] + defs + ['', f'end BioLean.Textbook.{mod}', '']
    (out / f'{mod}.lean').write_text('\n'.join(lines))
    print(f'{mod:40s} entities={len(ents)} statements={len(defs)}')
print('now claims', stats['now'], 'emitted', stats['emitted'])
print('skipped:', dict(skipped))
