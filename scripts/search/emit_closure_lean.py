"""Emit derived facts from the closure search as Lean Derivation terms over the compiled textbook
statements, so the kernel certifies what the search proposed. Usage: emit_closure_lean.py <n>"""
import json, re, glob, sys, collections
N = int(sys.argv[1]) if len(sys.argv) > 1 else 40
ders = json.load(open('data/search/derivations.json'))
# statement id -> Lean module.def
sid_mod = {}
for f in glob.glob('BioLean/Lib/TextbookClaimsR2/*.lean'):
    mod = f.split('/')[-1][:-5]
    if mod == 'Entities': continue
    for m in re.finditer(r'^def (\w+) : Statement where\n  id := "([^"]+)"', open(f).read(), re.M):
        sid_mod[m.group(2)] = f'{mod}.{m.group(1)}'
def rel_term(r):  # ['ro', 2234, False] -> Lean
    ns, num, inv = r
    return 'Rel.isA' + ('.flip' if inv else '') if ns == 'rdfs' else f'⟨.{ns}, {num}, {"true" if inv else "false"}⟩'
UNSUPPORTED = {'isaInheritEffect'}   # no Lean rule yet: a is_a b, b →s t  ⊢  a →s t
def term(d):
    r = d['rule']
    if r == 'lit': return f'(Derivation.lit {sid_mod[d["sid"]]})'
    p = [term(x) for x in d['premises']]
    if r in ('relChain', 'relTrans', 'isaInherit', 'isaGeneralise'):
        r3 = d['key'][1]  # the conclusion relation, from the fact key ['rel', [ns, num, inv], a, b]
        return f'(Derivation.relChain (r₃ := {rel_term(r3)}) {p[0]} {p[1]})'
    if r == 'relInv': return f'(Derivation.relInv {p[0]} {rel_term(d["to_rel"])})'
    if r == 'notRelSub': return f'(Derivation.notRelSub {p[0]} {p[1]})'
    if r == 'viaAmount': return f'(Derivation.viaAmount {p[0]} {p[1]})'
    if r == 'viaActivity': return f'(Derivation.viaActivity {p[0]} {p[1]})'
    raise KeyError(r)
def has_effect_chain(d):
    return d['rule'] in ('viaAmount','viaActivity') or any(has_effect_chain(x) for x in d.get('premises', []))
def ok(d):
    if d['rule'] == 'lit': return d['sid'] in sid_mod
    return d['rule'] not in UNSUPPORTED and all(ok(x) for x in d['premises'])
chosen = [d for d in ders if ok(d)][:N]
skipped = collections.Counter(d['rule'] for d in ders if not ok(d))
lines = ['import BioLean.Derivation', 'import BioLean.Lib.TextbookClaimsR2.CellStructureAndFunction', 'import BioLean.Lib.TextbookClaimsR2.HowCellsObtainEnergy',
         'import BioLean.Lib.TextbookClaimsR2.MolecularBiology', 'import BioLean.Lib.TextbookClaimsR2.Photosynthesis',
         'import BioLean.Lib.TextbookClaimsR2.ReproductionAtTheCellularLevel', 'import BioLean.Lib.TextbookClaimsR2.TheBodySSystemsA',
         'import BioLean.Lib.TextbookClaimsR2.TheBodySSystemsB', 'import BioLean.Lib.TextbookClaimsR2.TheCellularBasisOfInheritance', '',
         '/-! # Closure: facts the search derived from the textbook, certified by the kernel', '',
         'Generated by `scripts/search/emit_closure_lean.py` from `data/search/derivations.json`. Each `def` is a',
         'derivation the forward chainer proposed; Lean checks its shape, and `Established` its strength. -/', '',
         'namespace BioLean.Textbook.R2.Closure', 'open BioLean BioLean.Textbook.R2 Derivation', '']
for i, d in enumerate(chosen):
    th = '6/10' if has_effect_chain(d) else '7/10'
    lines += [f'/-- {d["fact"][:150]} -/', f'def c{i} := {term(d)}', f'example : Established (claim c{i}) ({th}) := ⟨c{i}, by decide +kernel⟩', '']
lines += ['-- one full report', '#eval IO.println c0.report', '', 'end BioLean.Textbook.R2.Closure', '']
open('BioLean/Examples/Closure.lean', 'w').write('\n'.join(lines))
print(f'emitted {len(chosen)} derivations; skipped by rule {dict(skipped)}')
